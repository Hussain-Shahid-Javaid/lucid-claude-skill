"""Evaluation & research runner: `lucid eval run [--split heldout|dev] [--out reports/]`.

Separates: software tests (pytest) | offline mechanism evaluations (this runner) |
live-model evaluations (not run without credentials) | research experiments.
Every number in the generated report is computed by this run; nothing is hand-written.
"""
from __future__ import annotations

import argparse
import json
import os
import platform
import sys
import time

from ..core import Lucid
from . import correction_suite, memory_suite
from .stats import mean, paired_bootstrap_ci, sign_test_p, wilson


def _prereg(path: str) -> dict:
    with open(path) as fh:
        return json.load(fh)


def run_memory(cfg: dict, split: str) -> dict:
    sp = cfg[split]
    out = {}
    for style in cfg["query_styles"]:
        t0 = time.time()
        r = memory_suite.run(sp["seed"], sp["n"], cfg["budget_tokens"], paraphrase=(style == "paraphrase"))
        base, treat = cfg["primary_comparison"]
        d = paired_bootstrap_ci(r[base], r[treat])
        out[style] = {
            "n": sp["n"], "seed": sp["seed"], "budget_tokens": cfg["budget_tokens"],
            "accuracy": {c: {"mean": round(mean(v), 3), "wilson95": [round(x, 3) for x in wilson(sum(v), len(v))]}
                         for c, v in r.items()},
            "primary_diff": {"comparison": f"{treat} - {base}", "mean": round(d[0], 3),
                             "ci95": [round(d[1], 3), round(d[2], 3)], "sign_test_p": sign_test_p(r[base], r[treat])},
            "hybrid_vs_retrieval": [round(x, 3) for x in paired_bootstrap_ci(r["lucid_retrieval"], r["lucid_hybrid"])],
            "wall_s": round(time.time() - t0, 2),
        }
    return out


def run_correction(cfg: dict, split: str) -> dict:
    sp = cfg[split]
    r = correction_suite.run(sp["seed"], sp["n"])
    n_init_correct = sum(1 for i in range(sp["n"]) if r["no_review"]["final_correct"][i])
    res = {"n": sp["n"], "seed": sp["seed"], "initially_correct": n_init_correct, "conditions": {}}
    for c, d in r.items():
        corr = sum(d["corrupted"])
        fixed = sum(d["fixed"])
        res["conditions"][c] = {
            "final_correct": round(mean(d["final_correct"]), 3),
            "corruption_rate": round(corr / max(1, n_init_correct), 3),
            "corruption_wilson95": [round(x, 3) for x in wilson(corr, n_init_correct)],
            "fix_rate": round(fixed / max(1, sp["n"] - n_init_correct), 3),
        }
    a, b = cfg["primary_comparison"]
    idx = [i for i in range(sp["n"]) if r["no_review"]["final_correct"][i]]
    d = paired_bootstrap_ci([r[a]["corrupted"][i] for i in idx], [r[b]["corrupted"][i] for i in idx])
    res["primary_diff"] = {"comparison": f"corruption({b}) - corruption({a})", "mean": round(d[0], 3),
                           "ci95": [round(d[1], 3), round(d[2], 3)]}
    return res


def render(report: dict) -> str:
    m, c = report["memory_suite"], report["correction_suite"]
    L = ["# Lucid evaluation report", "",
         f"Generated by `lucid eval run --split {report['split']}` at {report['generated_at']} "
         f"(Python {report['python']}). All numbers below were computed by this run.", "",
         "## What this does and does not show", "",
         "- These are **offline mechanism evaluations** with deterministic generated data and simulated agents.",
         "- They do **not** measure end-to-end assistant reasoning. The live-model suite is **not run** "
         f"({report['live_model_suite']['requires']}).",
         "- Passing software tests (pytest) is separate and does not imply improved reasoning.",
         f"- Development exposure: {report['preregistration_note']}", "",
         "## Memory retrieval (fixed context budget)", ""]
    for style, s in m.items():
        L += [f"### Query style: {style} (n={s['n']}, seed={s['seed']}, budget={s['budget_tokens']} tokens)", "",
              "| condition | accuracy | 95% Wilson CI |", "|---|---|---|"]
        for cond, v in s["accuracy"].items():
            L.append(f"| {cond} | {v['mean']} | {v['wilson95'][0]}–{v['wilson95'][1]} |")
        p = s["primary_diff"]
        L += ["", f"Primary ({p['comparison']}): {p['mean']} (paired bootstrap 95% CI {p['ci95'][0]}–{p['ci95'][1]}; "
                  f"sign test p={p['sign_test_p']:.3g}).",
              f"Hybrid backfill vs. plain retrieval: {s['hybrid_vs_retrieval'][0]} "
              f"(CI {s['hybrid_vs_retrieval'][1]}–{s['hybrid_vs_retrieval'][2]}).", ""]
    L += ["**Interpretation.** With keyword-overlapping queries, supersession-aware retrieval keeps the current "
          "value in a small budget far more often than the baselines (a ceiling result on a task whose queries "
          "share vocabulary with the stored facts by construction; baselines are deliberately simple). With paraphrased queries that share no "
          "vocabulary with the stored facts, Lucid's lexical retrieval is **worse than simple recency** — a real "
          "regression for that query style. Recency backfill did not fix it. Optional embedding retrieval is the "
          "planned mitigation and is not implemented.", "",
          f"## Correction cycle under a noisy reviser (n={c['n']}, seed={c['seed']}, "
          f"{c['initially_correct']} drafts initially correct)", "",
          "| condition | final correct | corruption rate (95% CI) | fix rate |", "|---|---|---|---|"]
    for cond, v in c["conditions"].items():
        L.append(f"| {cond} | {v['final_correct']} | {v['corruption_rate']} ({v['corruption_wilson95'][0]}–"
                 f"{v['corruption_wilson95'][1]}) | {v['fix_rate']} |")
    p = c["primary_diff"]
    L += ["", f"Primary ({p['comparison']}): {p['mean']} (95% CI {p['ci95'][0]}–{p['ci95'][1]}).", "",
          "**Interpretation.** The regression guard prevents a noisy reviser from damaging initially-correct "
          "answers in this simulation while still accepting genuine fixes. The reviser is a random proposal "
          "generator, so effect sizes say nothing about a specific model.", "",
          "## Live-model comparisons", "",
          f"Status: **{report['live_model_suite']['status']}**. Planned conditions: "
          f"{', '.join(report['live_model_suite']['conditions'])}.", ""]
    L += ["## Research experiments", ""]
    for e in report["experiments"]:
        L += [f"### {e['title']} — `{e['status']}`", "", f"- Hypothesis: {e['hypothesis']}",
              f"- Prediction: {e['prediction']}", f"- Result: `{json.dumps(e['result'], default=str)[:1500]}`",
              f"- Criticism / limits: {e['criticism']}", ""]
    return "\n".join(L)


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(prog="lucid eval")
    p.add_argument("action", choices=["run"])
    p.add_argument("--split", choices=["dev", "heldout"], default="heldout")
    p.add_argument("--prereg", default=os.path.join(os.getcwd(), "evals", "preregistration.json"))
    p.add_argument("--out", default=os.path.join(os.getcwd(), "reports"))
    p.add_argument("--db", default=None, help="record experiments in this Lucid DB (default: reports/experiments.db)")
    a = p.parse_args(argv)
    pre = _prereg(a.prereg)
    os.makedirs(a.out, exist_ok=True)
    dbp = a.db or os.path.join(a.out, "experiments.db")
    if os.path.exists(dbp) and not a.db:
        os.remove(dbp)
    L = Lucid(dbp)
    from ..research_modules import consciousness, discovery
    t0 = time.time()
    report = {
        "split": a.split, "generated_at": L.store.clock.iso(), "python": platform.python_version(),
        "preregistration_note": pre["note"],
        "memory_suite": run_memory(pre["memory_suite"], a.split),
        "correction_suite": run_correction(pre["correction_suite"], a.split),
        "live_model_suite": pre["live_model_suite"],
    }
    for mod in (discovery, consciousness):
        mod.run_all(L.experiments)
    report["experiments"] = L.experiments.list()
    report["wall_s"] = round(time.time() - t0, 2)
    report["cost"] = {"model_calls": 0, "tokens": 0, "usd": 0.0}
    with open(os.path.join(a.out, f"evaluation-{a.split}.json"), "w") as fh:
        json.dump(report, fh, indent=2, default=str)
    with open(os.path.join(a.out, f"evaluation-{a.split}.md"), "w") as fh:
        fh.write(render(report))
    L.close()
    print(f"wrote {a.out}/evaluation-{a.split}.md and .json ({report['wall_s']}s, 0 model calls)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
